"""Package the lab results for the local paper-trading dashboard.

The Mac mini must be able to replay the monthly scores without pandas or
LightGBM, so this writes a small numpy panel (from 2023-12-01) plus one
``[stock, day]`` score matrix per model.  Scores are finite only on month-end
signal days; the account engine treats those as rebalance dates.
"""
from __future__ import annotations

import json
import os
import shutil
from pathlib import Path

import numpy as np

ROOT = Path(os.environ.get("MF_ROOT", "/mnt/storage1/syk/experiments/Share/multifactor"))
PANEL = ROOT / "panel" / "panel.npz"
FACTORS = ROOT / "factors" / "factors.npz"
RESULTS = ROOT / "results"
OUT = ROOT / "local_export"
START = "2023-12-01"

MODELS = ("mf_lgbm", "mf_equal", "mf_size")
MODEL_META = {
    "mf_lgbm": {
        "id": "mf-lgbm",
        "name": "多因子 LightGBM",
        "short": "多因子 LGBM",
        "color": "#c62828",
        "note": "14 因子 · LightGBM 3 种子 · 按本金 4–40 只",
    },
    "mf_equal": {
        "id": "mf-equal",
        "name": "多因子等权",
        "short": "多因子等权",
        "color": "#1f6feb",
        "note": "14 因子截面 z 分数等权 · 按本金 4–40 只",
    },
    "mf_size": {
        "id": "mf-size",
        "name": "纯小市值",
        "short": "小市值",
        "color": "#0a9b5a",
        "note": "只按流通市值最小排序 · 按本金 4–40 只",
    },
}


def main() -> None:
    panel = np.load(PANEL)
    factors = np.load(FACTORS)
    dates = [str(item) for item in panel["dates"]]
    start = int(np.searchsorted(dates, START))
    month_indices = factors["month_indices"].astype(int)
    month_dates = [str(item) for item in factors["month_dates"]]
    keep_months = [i for i, day in enumerate(month_indices) if day >= start]
    scores = np.load(RESULTS / "scores.npz")

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "scores").mkdir(exist_ok=True)
    np.savez(
        OUT / "panel.npz",
        dates=np.array(dates[start:], dtype="U10"),
        stocks=panel["stocks"],
        names=panel["names"],
        close=panel["close"][:, start:],
        pct_chg=panel["pct_chg"][:, start:],
        is_st=panel["is_st"][:, start:],
        tradable=panel["tradable"][:, start:],
        float_mcap=panel["float_mcap"][:, start:],
        listed_days=panel["listed_days"][:, start:],
        benchmark_close=panel["benchmark_close"][start:],
    )
    n_stocks, n_days = len(panel["stocks"]), len(dates) - start
    for model in MODELS:
        daily = np.full((n_stocks, n_days), np.nan, dtype=np.float32)
        for month in keep_months:
            day = int(month_indices[month]) - start
            if 0 <= day < n_days:
                daily[:, day] = scores[model][:, month].astype(np.float32)
        np.savez(OUT / "scores" / f"{model}_ensemble.npz", score=daily)

    metadata = {
        "dates": dates[start:],
        "stocks": [str(item) for item in panel["stocks"]],
        "names": [str(item) for item in panel["names"]],
        "month_dates": [month_dates[i] for i in keep_months],
        "signal_days": [int(month_indices[i] - start) for i in keep_months],
        "models": {model: MODEL_META[model] for model in MODELS},
        "universe": "all currently listed A-shares; small-cap pool = smallest 30% of eligible by float market cap",
        "fee_note": "buy 0.10% / sell 0.20%, minimum 5 CNY per trade, 1% previous-day amount cap",
    }
    (OUT / "metadata.json").write_text(json.dumps(metadata, ensure_ascii=False, indent=1), encoding="utf-8")
    config = {
        "portfolio_size": {"10000": 4, "30000": 8, "50000": 10, "100000": 40},
        "buffer_size": {"10000": 4, "30000": 8, "50000": 10, "100000": 40},
        "max_replace": {"10000": 4, "30000": 8, "50000": 10, "100000": 40},
        "rebalance_stride": 3,
        "lot_aware": False,
        "sweep_mode": "round_robin",
        "max_weight_mult": 2.0,
        "afford_mult": 1.5,
        "buy_cost": 0.001,
        "sell_cost": 0.002,
        "min_fee": 5.0,
        "liquidity": 0.01,
    }
    (OUT / "config.json").write_text(json.dumps(config, indent=2), encoding="utf-8")
    if (RESULTS / "metrics.json").exists():
        shutil.copy(RESULTS / "metrics.json", OUT / "metrics.json")
    for name in ("equity.png", "ic.png"):
        if (RESULTS / name).exists():
            shutil.copy(RESULTS / name, OUT / name)
    (OUT / "README.md").write_text(
        "# Small-cap multi-factor local export\n\n"
        "Replay data for the `multifactor` dashboard family. Generated by "
        "`export_local.py`; scores are monthly and finite only on signal days.\n",
        encoding="utf-8",
    )
    print(f"local export written to {OUT}: {n_stocks} stocks x {n_days} days, "
          f"{len(keep_months)} signal days")


if __name__ == "__main__":
    main()
